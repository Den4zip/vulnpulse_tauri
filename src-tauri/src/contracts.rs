#[derive(Serialize)]
#[serde(rename_all = "snake_case")]
#[cfg_attr(test, derive(TS))]
pub(crate) enum CommandErrorCode {
    InvalidRequest,
    Busy,
    Unavailable,
    NotFound,
}

#[derive(Serialize)]
#[cfg_attr(test, derive(TS))]
pub(crate) struct CommandError {
    pub code: CommandErrorCode,
}

impl From<CommandErrorCode> for CommandError {
    fn from(code: CommandErrorCode) -> Self {
        Self { code }
    }
}

#[cfg(test)]
mod tests {
    use std::{fs, path::PathBuf};

    use super::*;

    fn declarations() -> String {
        let types = [
            ListDemoCatalogRequest::decl(),
            DemoEntryDto::decl(),
            ListDemoCatalogResponse::decl(),
            Severity::decl(),
            SourceKind::decl(),
            CatalogSort::decl(),
            SortDirection::decl(),
            CatalogQueryRequest::decl(),
            CatalogEntryDto::decl(),
            CatalogSummaryDto::decl(),
            CatalogPageDto::decl(),
            CatalogDetailRequest::decl(),
            SourceRecordDto::decl(),
            CatalogDetailDto::decl(),
            CommandErrorCode::decl(),
            CommandError::decl(),
        ];
        format!(
            "// Generated by npm run contracts:generate.\n\nexport {}\n",
            types.join("\n\nexport ")
        )
    }

    fn output_path() -> PathBuf {
        PathBuf::from(env!("CARGO_MANIFEST_DIR")).join("../src/generated/contracts.ts")
    }

    #[test]
    fn typescript_contracts_are_current() {
        let current = fs::read_to_string(output_path()).expect("run npm run contracts:generate");
        assert_eq!(
            current.replace("\r\n", "\n"),
            declarations(),
            "run npm run contracts:generate"
        );
    }

    #[test]
    #[ignore = "run explicitly to update the checked-in TypeScript declarations"]
    fn generate_typescript_contracts() {
        let path = output_path();
        fs::create_dir_all(path.parent().unwrap()).unwrap();
        fs::write(path, declarations()).unwrap();
    }
}
